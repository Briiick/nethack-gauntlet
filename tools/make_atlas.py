#!/usr/bin/env python3
"""Build the tile atlas and glyph table for NetHack Gauntlet.

Inputs (from a NetHack 5.0 source tree):
  win/share/{monsters,objects,other}.txt   the official 16x16 tile art
  src/tile.c                               generated by util/tilemap; maps every glyph to a tile

Outputs:
  public/assets/atlas.png    every tile restyled (dark outline on sprites), 18x18 cells
  public/assets/tiles.json   glyph -> tile index, glyph -> render class, tile names

Usage: python3 tools/make_atlas.py <nethack-src-dir> <out-assets-dir>
"""
import json
import re
import sys
from pathlib import Path

from PIL import Image

SRC = Path(sys.argv[1])
OUT = Path(sys.argv[2])
CELL = 18          # 16px tile + 1px pad on each side for the outline
COLS = 48
OUTLINE = (8, 6, 10, 255)
FILES = ['monsters.txt', 'objects.txt', 'other.txt']


def parse_tiles(path):
    pal, tiles, cur, name = {}, [], None, None
    for line in path.read_text().splitlines():
        m = re.match(r"^(\S) = \((\d+),\s*(\d+),\s*(\d+)\)", line)
        if m:
            pal[m.group(1)] = tuple(int(m.group(i)) for i in (2, 3, 4))
            continue
        m = re.match(r"^# tile (\d+) \((.*)\)", line)
        if m:
            name = m.group(2)
            continue
        if line.strip() == '{':
            cur = []
        elif line.strip() == '}':
            tiles.append((name, cur))
            cur = None
        elif cur is not None:
            cur.append(line.strip())
    return pal, tiles


def tile_image(pal, rows, outline, gray=False, transparent=None):
    """Render one 16x16 tile into an 18x18 cell.

    Stock NetHack tiles sit on a black (or teal) background. For sprites we
    flood-fill that background from the tile edge to transparency, so black
    detail inside a sprite (eyes, outlines) survives, then add a dark outline.
    """
    im = Image.new('RGBA', (CELL, CELL), (0, 0, 0, 0))
    px = im.load()
    teal = (71, 108, 108)
    grid = [[pal.get(ch, teal) for ch in r] for r in rows]
    h, w = len(grid), max(len(r) for r in grid)
    clear = set()
    if transparent is None:
        transparent = outline
    if transparent:
        stack = [(x, y) for x in range(w) for y in (0, h - 1)] + [(x, y) for y in range(h) for x in (0, w - 1)]
        while stack:
            x, y = stack.pop()
            if (x, y) in clear or not (0 <= x < w and 0 <= y < h) or x >= len(grid[y]):
                continue
            if grid[y][x] not in (teal, (0, 0, 0)):
                continue
            clear.add((x, y))
            stack.extend(((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)))
    solid = set()
    for y, r in enumerate(grid):
        for x, c in enumerate(r):
            if c == teal or (x, y) in clear:
                continue
            if gray:
                l = int(c[0] * .3 + c[1] * .59 + c[2] * .11)
                c = (int(l * .92), int(l * .94), int(l * 1.0))
            px[x + 1, y + 1] = c + (255,)
            solid.add((x, y))
    if outline:
        for (x, y) in list(solid):
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                nx, ny = x + dx, y + dy
                if (nx, ny) not in solid and -1 <= nx <= 16 and -1 <= ny <= 16:
                    px[nx + 1, ny + 1] = OUTLINE
    return im


def classify_other(name):
    """Render class for terrain / effect tiles (other.txt)."""
    n = name.lower()
    if 'walls' in n:
        return 'wall', n.split(' walls')[0].split()[-1]
    table = [
        ('dark part of a room', 'darkfloor'), ('floor of a room', 'floor'), ('lit corridor', 'litcorr'),
        ('corridor', 'corr'), ('doorway', 'doorway'), ('open door', 'opendoor'), ('closed door', 'closeddoor'),
        ('engraving', 'engraving'), ('stone', 'stone'), ('unexplored', 'void'), ('nothing', 'void'),
        ('molten lava', 'lava'), ('wall of lava', 'lava'), ('water', 'water'), ('ice', 'ice'), ('air', 'air'),
        ('cloud', 'cloud'), ('iron bars', 'bars'), ('tree', 'tree'), ('drawbridge', 'feature'),
        ('zap', 'zap'), ('beam', 'zap'), ('boom', 'zap'), ('shield', 'zap'), ('explosion', 'explosion'),
        ('swallow', 'swallow'), ('warning', 'warning'), ('poison cloud', 'cloud'), ('valid position', 'cursor'),
        ('trap', 'trap'), ('pit', 'trap'), ('hole', 'trap'), ('web', 'trap'), ('board', 'trap'),
        ('land mine', 'trap'), ('portal', 'trap'), ('teleporter', 'trap'), ('anti-magic', 'trap'),
        ('vibrating square', 'trap'), ('trapped', 'trap'),
    ]
    if n in ('air', 'cloud'):
        return n, ''
    for key, cls in table:
        if key in ('air', 'cloud'):
            continue
        if key in n:
            return cls, ''
    return 'feature', ''  # stairs, ladders, altars, grave, throne, sink, fountain


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    tiles = []   # (file, local idx, name, image-rows, palette)
    file_base = {}
    for f in FILES:
        pal, ts = parse_tiles(SRC / 'win' / 'share' / f)
        file_base[f] = len(tiles)
        for i, (name, rows) in enumerate(ts):
            tiles.append((f, i, name, rows, pal))
    n_src = len(tiles)

    pat = re.compile(r"NO_CUSTOMCOLOR,\s*NO_CUSTOMCOLOR,\s*(\d+),\s*\d+\s*\},\s*/\* \[(\d+)\] (\S+?):(\d+)\s+(.*?)\s*\*/")
    glyphs = {}
    for line in (SRC / 'src' / 'tile.c').read_text().splitlines():
        m = pat.search(line)
        if m:
            glyphs[int(m.group(2))] = (int(m.group(1)), m.group(3), int(m.group(4)), m.group(5))
    max_glyph = max(glyphs) + 1
    total = max(t for t, *_ in glyphs.values()) + 1

    # atlas: source tiles first, then generated statue tiles
    rows_n = (total + COLS - 1) // COLS
    atlas = Image.new('RGBA', (COLS * CELL, rows_n * CELL), (0, 0, 0, 0))
    names = [''] * total
    for idx, (f, i, name, rows, pal) in enumerate(tiles):
        solid_terrain = f == 'other.txt' and any(k in name for k in (
            'walls', 'floor', 'corridor', 'stone', 'water', 'lava', 'ice', 'dark part', 'door', 'unexplored', 'nothing', 'air', 'cloud', 'explosion', 'swallow'))
        im = tile_image(pal, rows, outline=(f != 'other.txt'), transparent=not solid_terrain)
        atlas.alpha_composite(im, ((idx % COLS) * CELL, (idx // COLS) * CELL))
        names[idx] = name
    for g, (tidx, f, local, desc) in glyphs.items():
        if f == 'generated' and tidx >= n_src and not names[tidx]:
            mf, mi, mname, mrows, mpal = tiles[file_base['monsters.txt'] + local]
            im = tile_image(mpal, mrows, outline=True, gray=True)
            atlas.alpha_composite(im, ((tidx % COLS) * CELL, (tidx // COLS) * CELL))
            names[tidx] = 'statue of ' + mname

    g2t, gcls, gtheme, gname, gmon, gobj = [], [], [], [], [], []
    classes, themes = [], ['']
    for g in range(max_glyph):
        tidx, f, local, desc = glyphs.get(g, (0, 'other.txt', 0, 'unknown'))
        if f == 'monsters.txt':
            cls, theme = 'mon', ''
        elif f == 'objects.txt':
            cls, theme = 'obj', ''
        elif f == 'generated':
            cls, theme = 'statue', ''
        else:
            cls, theme = classify_other(desc.replace('cmap A ', '').replace('cmap B ', ''))
        if cls not in classes:
            classes.append(cls)
        if theme not in themes:
            themes.append(theme)
        g2t.append(tidx)
        gcls.append(classes.index(cls))
        gtheme.append(themes.index(theme))
        mm = re.search(r'\(mnum=(\d+)\)', desc)
        gmon.append(int(mm.group(1)) if mm else -1)
        om = re.search(r'\(onum=(\d+)\)', desc)
        gobj.append(int(om.group(1)) if om else (-2 if f == 'objects.txt' else -1))   # object type; -2: corpse, fixed below
        gname.append(re.sub(r'\s*\((mnum|onum|cmap|warn)=\d+\)|\s*\(\d+\)', '', desc).strip())

    # per-monster "body of X" glyphs name the monster, not the object: they are all corpses
    corpse = next(gobj[g] for g in range(max_glyph) if gname[g] == 'corpse' and gobj[g] >= 0)
    gobj = [corpse if o == -2 else o for o in gobj]

    atlas.save(OUT / 'atlas.png', optimize=True)
    data = {
        'cell': CELL, 'cols': COLS, 'tiles': total, 'glyphs': max_glyph,
        'classes': classes, 'themes': themes,
        'g2t': g2t, 'gcls': gcls, 'gtheme': gtheme, 'gname': gname, 'gmon': gmon, 'gobj': gobj,
    }
    (OUT / 'tiles.json').write_text(json.dumps(data, separators=(',', ':')))
    print(f'{n_src} source tiles, {total} atlas cells, {max_glyph} glyphs, classes={classes}')


if __name__ == '__main__':
    main()
